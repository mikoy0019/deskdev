// Writes DeskDev's service-worker source (src/deskdev/pwa/sw/sw.js) into
// src/deskdev/pwa/sw/swSource.ts as one string, which the workspace sw.js
// route serves (src/app/workspace/sw.js/route.ts). The route can't read the
// file at run time (a Worker has no file system), and importing a .js file as
// text is bundler-specific, so the text is a plain module instead.
//
// Runs before `next dev` and `next build` (package.json predev / prebuild);
// src/deskdev/pwa/sw/swSource.test.ts fails if the committed file is stale.
// Line endings are LF whatever the checkout has, so Windows and CI agree.
//
//   node scripts/sw-source.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const SOURCE_PATH = resolve(HERE, '../src/deskdev/pwa/sw/sw.js');
export const MODULE_PATH = resolve(HERE, '../src/deskdev/pwa/sw/swSource.ts');

/** The module for a given sw.js text. */
export function renderSourceModule(text) {
  const source = text.replace(/\r\n/g, '\n');
  return [
    '// GENERATED by scripts/sw-source.mjs from sw.js — do not hand-edit; change',
    '// sw.js and run the script (predev / prebuild do).',
    '',
    `export const SW_SOURCE: string = ${JSON.stringify(source)};`,
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const next = renderSourceModule(readFileSync(SOURCE_PATH, 'utf8'));
  let current = '';
  try {
    current = readFileSync(MODULE_PATH, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    // First run: no module yet.
  }
  if (current !== next) writeFileSync(MODULE_PATH, next);
}
