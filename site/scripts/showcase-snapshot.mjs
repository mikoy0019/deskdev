// Prebuild snapshot of the public showcase into src/content/showcase-fallback.ts.
//
// The site reads /portfolio from Supabase (src/lib/showcase.ts) and falls back
// to that committed file whenever Supabase can't answer. Run before every build
// (`"prebuild": "node scripts/showcase-snapshot.mjs"`) so the fallback is never
// older than the last deploy: a takedown done in DeskDev must not come back
// the next time Supabase is paused.
//
// Reads the same anon surface the site does (NEXT_PUBLIC_SUPABASE_URL and
// NEXT_PUBLIC_SUPABASE_ANON_KEY, column grants + the status='published' policy),
// so it can only ever write what anon may already see. It never fails the
// build: missing env, a network error, an error status or zero rows keep the
// committed file as it is. `--strict` turns those into exit 1 (for CI), and
// `--dry-run` reports without writing.
//
//   node scripts/showcase-snapshot.mjs [--dry-run] [--strict]

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const FALLBACK_PATH = resolve(HERE, '../src/content/showcase-fallback.ts');

/**
 * The columns anon is granted on showcase_items (037). PostgREST answers
 * `select=*` with a permission error under column grants, so both readers
 * name them. Must match SHOWCASE_COLUMNS in src/lib/showcase.ts (a test
 * checks it).
 */
export const SHOWCASE_COLUMNS = [
  'slug',
  'kind',
  'title',
  'url',
  'link_public',
  'industry',
  'summary',
  'result_tag',
  'stack',
  'accent',
  'mockup_variant',
  'image_key',
  'image_key_small',
  'image_alt',
  'image_source',
  'case_study',
  'featured',
  'home_featured',
  'sort_order',
  'launched_on',
  'published_at',
];

/** anon reads `public_url` (037), aliased back to the `url` row key. */
export const SHOWCASE_SELECT = SHOWCASE_COLUMNS.map((col) => (col === 'url' ? 'url:public_url' : col)).join(',');

const KINDS = new Set(['website', 'web_app', 'product']);
const TIMEOUT_MS = 10_000;

/** A row as the fallback stores it: the public columns plus its status. */
export function toFallbackRow(row, status = 'published') {
  if (!row || typeof row !== 'object') return null;
  if (typeof row.slug !== 'string' || !row.slug) return null;
  if (typeof row.title !== 'string' || !row.title) return null;
  if (!KINDS.has(row.kind)) return null;
  const out = {};
  for (const col of SHOWCASE_COLUMNS) out[col] = row[col] ?? defaultFor(col);
  out.status = status;
  return out;
}

function defaultFor(col) {
  if (col === 'link_public') return true;
  if (col === 'featured' || col === 'home_featured') return false;
  if (col === 'sort_order') return 0;
  if (col === 'stack') return [];
  return null;
}

/** Stable order so an unchanged showcase writes a byte-identical file. */
export function sortRows(rows) {
  return [...rows].sort((a, b) => (a.sort_order ?? 0) - (b.sort_order ?? 0) || a.slug.localeCompare(b.slug));
}

// Single-quoted JS literals, to read like the rest of the site's source.
function lit(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'string') {
    // JSON escapes quotes, backslashes and control characters; then swap the
    // double-quote delimiters for single ones.
    return `'${JSON.stringify(value).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'")}'`;
  }
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'null';
  if (typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) return `[${value.map(lit).join(', ')}]`;
  if (typeof value === 'object') {
    const entries = Object.entries(value).map(([k, v]) => `${/^[A-Za-z_$][\w$]*$/.test(k) ? k : lit(k)}: ${lit(v)}`);
    return entries.length ? `{ ${entries.join(', ')} }` : '{}';
  }
  return 'null';
}

export function renderFallbackModule(rows) {
  const body = sortRows(rows)
    .map((row) => `  ${lit(row)},`)
    .join('\n');
  return `// GENERATED by scripts/showcase-snapshot.mjs — do not hand-edit; change the
// showcase in DeskDev and rebuild. The first version is the hardcoded /portfolio
// data moved verbatim (8 products, 80 client sites; the 12 sites whose capture
// showed an error page sit in 'ready', as the 038 seed has them).
//
// src/lib/showcase.ts serves this only when Supabase can't answer, keeps only
// the 'published' rows, and never caches it.

import type { ShowcaseFallbackRow } from '../lib/showcase';

export const SHOWCASE_FALLBACK: readonly ShowcaseFallbackRow[] = [
${body}
];
`;
}

async function fetchPublishedRows(base, key) {
  const url = new URL('/rest/v1/showcase_items', base);
  url.searchParams.set('select', SHOWCASE_SELECT);
  url.searchParams.set('order', 'sort_order.asc,slug.asc');
  const headers = { apikey: key, Accept: 'application/json' };
  // Legacy anon keys are JWTs and go in Authorization too; the newer
  // sb_publishable_ keys are not JWTs and must not.
  if (key.startsWith('eyJ')) headers.Authorization = `Bearer ${key}`;
  const res = await fetch(url, { headers, signal: AbortSignal.timeout(TIMEOUT_MS) });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const data = await res.json();
  if (!Array.isArray(data)) throw new Error('response is not an array');
  return data;
}

async function main(argv) {
  const dryRun = argv.includes('--dry-run');
  const strict = argv.includes('--strict');
  const keep = (why) => {
    console.log(`[showcase-snapshot] keeping the committed fallback: ${why}`);
    return strict ? 1 : 0;
  };

  const base = process.env.NEXT_PUBLIC_SUPABASE_URL?.trim();
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY?.trim();
  if (!base || !key) return keep('NEXT_PUBLIC_SUPABASE_URL / NEXT_PUBLIC_SUPABASE_ANON_KEY not set');

  let raw;
  try {
    raw = await fetchPublishedRows(base, key);
  } catch (err) {
    return keep(`fetch failed (${err instanceof Error ? err.message : String(err)})`);
  }
  const rows = raw.map((r) => toFallbackRow(r)).filter(Boolean);
  if (rows.length === 0) return keep('Supabase returned no published rows');

  const next = renderFallbackModule(rows);
  const current = await readFile(FALLBACK_PATH, 'utf8').catch(() => '');
  if (current === next) {
    console.log(`[showcase-snapshot] unchanged (${rows.length} published rows)`);
    return 0;
  }
  if (dryRun) {
    console.log(`[showcase-snapshot] --dry-run: would write ${rows.length} published rows`);
    return 0;
  }
  await writeFile(FALLBACK_PATH, next, 'utf8');
  console.log(`[showcase-snapshot] wrote ${rows.length} published rows to src/content/showcase-fallback.ts`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  // Not process.exit(): on Windows it can abort inside libuv while the fetch's
  // socket is still closing, and a prebuild that crashes fails the whole build.
  main(process.argv.slice(2)).then((code) => {
    process.exitCode = code;
  });
}
