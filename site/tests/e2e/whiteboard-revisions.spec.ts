import { test, expect } from '@playwright/test'

test('tasks have list view, a right details panel, comments and context actions', async ({ page }) => {
  await page.goto('/workspace/tasks')
  const card = page.locator('[data-card-id="t-auth"]')
  await expect(card).toBeVisible()
  await card.getByText('Wire up auth flow', { exact: true }).click({ button: 'right' })
  const menu = page.getByRole('dialog', { name: 'Task actions', exact: true })
  await expect(menu.getByRole('button', { name: 'Duplicate task', exact: true })).toBeVisible()
  await menu.getByRole('button', { name: 'Open task details', exact: true }).click()
  const details = page.getByRole('dialog', { name: 'Edit task', exact: true })
  await expect(details).toBeVisible()
  await expect.poll(async () => {
    const bounds = await details.boundingBox()
    return Math.abs(bounds!.x + bounds!.width - page.viewportSize()!.width)
  }).toBeLessThan(1)
  await details.getByLabel('Add a comment', { exact: true }).fill('Please review this revision, ')
  await details.getByLabel('Mention teammate', { exact: true }).selectOption({ label: 'Alex Cruz' })
  await details.getByRole('button', { name: 'Post comment', exact: true }).click()
  await expect(details.getByRole('region', { name: 'Task comments' })).toContainText('@Alex Cruz')
  await details.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'List', exact: true }).click()
  await expect(page.getByRole('table')).toContainText('Wire up auth flow')
  await page.reload()
  await expect(page.getByRole('button', { name: 'List', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Wire up auth flow', exact: true }).click()
  await expect(details.getByRole('region', { name: 'Task comments' })).toContainText('Please review this revision')
})

test('task action forms do not open the details panel and preserve covers and subtasks', async ({ page }) => {
  await page.goto('/workspace/tasks')
  const card = page.locator('[data-card-id="t-auth"]')
  await card.getByRole('button', { name: 'Task actions: Wire up auth flow' }).click()
  await page.getByRole('dialog', { name: 'Task actions', exact: true }).getByRole('button', { name: 'Add subtask', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'Add subtask', exact: true })
  await form.getByLabel('Subtask title').fill('Review revised login flow')
  await expect(page.getByRole('dialog', { name: 'Edit task', exact: true })).toHaveCount(0)
  await form.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(form).toBeHidden()
  await card.getByRole('button', { name: 'Task actions: Wire up auth flow' }).click()
  await page.getByRole('dialog', { name: 'Task actions', exact: true }).getByRole('button', { name: 'Duplicate task', exact: true }).click()
  const details = page.getByRole('dialog', { name: 'Edit task', exact: true })
  await expect(details).toContainText('Review revised login flow')
  await details.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByText('Wire up auth flow (copy)', { exact: true })).toBeVisible()
})

