import { expect, test } from '@playwright/test'

test('agreement, deposit, approvals and later collection persist through reload', async ({ page }) => {
  await page.goto('/workspace/login')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.locator('#login-email').fill('admin@deskdev.local')
  await page.locator('#login-password').fill('admin')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.goto('/workspace/projects/pr-portal')
  const panel = page.getByRole('region', { name: 'Engagement', exact: true })
  await expect(panel).toBeVisible()
  await panel.getByLabel('Agreed fee', { exact: true }).fill('1000.00')
  await panel.getByLabel('Required deposit', { exact: true }).fill('250.00')
  await panel.getByLabel('Agreed scope and deliverables').fill('Client portal with approved dashboard')
  await panel.getByLabel('Acceptance date', { exact: true }).fill('2026-01-01')
  await panel.getByLabel('Acceptance evidence').fill('Signed contract A-1')
  await panel.getByLabel('New milestone', { exact: true }).fill('Dashboard delivery')
  await panel.getByLabel('Milestone due date').fill('2026-01-10')
  await panel.getByRole('button', { name: 'Add milestone', exact: true }).click()
  await panel.getByRole('button', { name: 'Save and start delivery' }).click()
  await expect(panel.getByRole('alert')).toContainText('deposit')

  await panel.getByLabel('Invoice reference', { exact: true }).fill('INV-1')
  await panel.getByLabel('Invoice amount', { exact: true }).fill('1000.00')
  await panel.getByLabel('Invoice due date').fill('2026-01-05')
  await panel.getByRole('button', { name: 'Add invoice', exact: true }).click()
  await panel.getByLabel('Receipt invoice').selectOption({ label: 'INV-1' })
  await panel.getByLabel('Payment reference').fill('TX-1')
  await panel.getByLabel('Amount received').fill('250.00')
  await panel.getByLabel('Received on').fill('2026-01-02')
  await panel.getByRole('button', { name: 'Add receipt', exact: true }).click()
  await panel.getByRole('button', { name: 'Save and start delivery' }).click()
  await expect(panel.getByRole('button', { name: 'Save and complete delivery' })).toBeVisible()
  await expect(panel.getByLabel('Agreed fee', { exact: true })).toBeDisabled()
  await panel.getByRole('button', { name: 'Save and complete delivery' }).click()
  await expect(panel.getByRole('alert')).toContainText('Approve every milestone')
  await panel.getByLabel('Status for Dashboard delivery').selectOption('approved')
  await panel.getByRole('button', { name: 'Save and complete delivery' }).click()
  await expect(panel.getByRole('alert')).toContainText('approval evidence')
  await panel.getByLabel('Approval evidence for Dashboard delivery').fill('Client email E-1')
  await panel.getByRole('button', { name: 'Save and complete delivery' }).click()
  await expect(panel.getByLabel('Status for Dashboard delivery')).toBeDisabled()

  await panel.getByLabel('Payment reference').fill('TX-2')
  await panel.getByLabel('Amount received').fill('750.00')
  await panel.getByLabel('Received on').fill('2026-01-03')
  await panel.getByRole('button', { name: 'Add receipt', exact: true }).click()
  await panel.getByRole('button', { name: 'Save engagement', exact: true }).click()
  await expect(panel.getByText(/INV-1.*Paid/)).toBeVisible()
  await page.reload()
  await expect(panel.getByText('TX-2 · INV-1 · 2026-01-03')).toBeVisible()
  await expect(panel.getByLabel('Agreed scope and deliverables')).toHaveValue('Client portal with approved dashboard')
  await page.setViewportSize({ width: 390, height: 844 })
  await panel.scrollIntoViewIfNeeded()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('members cannot see the engagement finance panel', async ({ page }) => {
  await page.goto('/workspace/login')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.locator('#login-email').fill('member@deskdev.local')
  await page.locator('#login-password').fill('member')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.goto('/workspace/projects/pr-portal')
  await expect(page.getByRole('heading', { name: 'Client portal redesign', exact: true, level: 2 })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Engagement', exact: true })).toHaveCount(0)
})
