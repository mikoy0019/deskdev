import { test, expect, type Page } from '@playwright/test'

test('people offer user actions and a direct message', async ({ page }) => {
  await page.goto('/workspace')
  await page.getByRole('button', { name: /^People:/ }).click()
  await page.getByRole('button', { name: 'User actions: Alex Cruz', exact: true }).click()
  const actions = page.getByRole('dialog', { name: 'User actions', exact: true })
  await expect(actions.getByRole('menuitem', { name: 'Message', exact: true })).toBeVisible()
  await actions.getByRole('menuitem', { name: 'Properties', exact: true }).click()
  const properties = page.getByRole('dialog', { name: 'User properties', exact: true })
  await expect(properties).toContainText('Alex Cruz')
  await properties.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'User actions: Alex Cruz', exact: true }).click()
  await actions.getByRole('menuitem', { name: 'Message', exact: true }).click()
  await expect(page).toHaveURL(/\/workspace\/messages\//)
  await expect(page.getByLabel('Write a message')).toBeVisible()
})

test('right-click menus offer properties and preserve text input menus', async ({ page }) => {
  await page.goto('/workspace/projects')
  const project = page.locator('[data-item-kind="project"]').first()
  await project.click({ button: 'right' })
  const actions = page.getByRole('dialog', { name: 'Item actions', exact: true })
  await expect(actions.getByRole('menuitem', { name: 'Open in a new tab' })).toHaveAttribute('href', /\/workspace\/projects\//)
  await actions.getByRole('menuitem', { name: 'Properties', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Item properties', exact: true })).toContainText('project')
  await page.getByRole('dialog', { name: 'Item properties', exact: true }).getByRole('button', { name: 'Close', exact: true }).click()
  await page.goto('/workspace/whiteboard')
  const search = page.getByLabel('Search boards', { exact: true })
  await search.click({ button: 'right' })
  await expect(actions).toBeHidden()
  await page.goto('/workspace/tasks')
  await page.locator('[data-card-id="t-auth"]').click({ button: 'right' })
  await expect(page.getByRole('dialog', { name: 'Task actions', exact: true }).getByRole('button', { name: 'Properties', exact: true })).toBeVisible()
})

async function rectangle(page: Page, x: number) {
  const canvas = page.locator('.excalidraw canvas').last()
  await expect(canvas).toBeVisible()
  await expect(page.locator('.excalidraw .LoadingMessage')).toBeHidden()
  const box = await canvas.boundingBox()
  const tool = page.getByRole('radio', { name: 'Rectangle', exact: true })
  await tool.locator('..').click()
  await expect(tool).toBeChecked()
  await page.mouse.move(box!.x + x, box!.y + 250)
  await page.mouse.down()
  await page.mouse.move(box!.x + x + 90, box!.y + 310, { steps: 4 })
  await page.mouse.up()
  await page.keyboard.press('Escape')
}

test('two whiteboard editors merge strokes live and retain them after refresh', async ({ page, context }) => {
  await page.goto('/workspace/whiteboard')
  await page.getByRole('button', { name: 'New whiteboard', exact: true }).first().click()
  await page.getByLabel('Board title', { exact: true }).fill('Concurrent editor proof')
  await page.getByRole('button', { name: 'Create and open', exact: true }).click()
  await expect(page.locator('.excalidraw canvas').last()).toBeVisible()
  const second = await context.newPage()
  await second.goto(page.url())
  await expect(second.locator('.excalidraw canvas').last()).toBeVisible()
  // Both editors stay open; use each tab's own toolbar and pointer in turn.
  // Simultaneous version-conditional writes are covered by the session tests.
  await rectangle(page, 220)
  await rectangle(second, 420)
  await expect(page.getByRole('status', { name: 'Drawing elements' })).toHaveText('2 shapes', { timeout: 20000 })
  await expect(second.getByRole('status', { name: 'Drawing elements' })).toHaveText('2 shapes', { timeout: 20000 })
  await expect(page.getByText(/^Saved/).first()).toBeVisible()
  await page.reload()
  await expect(page.getByRole('status', { name: 'Drawing elements' })).toHaveText('2 shapes')
  await second.close()
})

test('presence changes from active to away and back on interaction', async ({ page }) => {
  await page.clock.install()
  await page.goto('/workspace')
  await page.getByRole('button', { name: /^People:/ }).click()
  const me = page.getByRole('button', { name: 'User actions: Maykie', exact: true })
  await expect(me).toContainText('Active')
  await page.clock.fastForward(5 * 60 * 1000 + 1000)
  await expect(me).toContainText('Away')
  await page.keyboard.press('Shift')
  await expect(me).toContainText('Active')
})

test('an unsent drawing recovers after refresh and saves when storage returns', async ({ page }) => {
  await page.addInitScript(() => {
    const write = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key === 'deskdev-whiteboards:v1' && sessionStorage.getItem('proof-fail-board-write')) throw new DOMException('Simulated save outage', 'QuotaExceededError')
      write.call(this, key, value)
    }
  })
  await page.goto('/workspace/whiteboard')
  await page.getByRole('button', { name: 'New whiteboard', exact: true }).first().click()
  await page.getByLabel('Board title', { exact: true }).fill('Recovery proof')
  await page.getByRole('button', { name: 'Create and open', exact: true }).click()
  await expect(page.locator('.excalidraw canvas').last()).toBeVisible()
  await page.evaluate(() => sessionStorage.setItem('proof-fail-board-write', '1'))
  await rectangle(page, 280)
  await expect(page.getByRole('status', { name: 'Drawing elements' })).toHaveText('1 shapes')
  await expect(page.getByRole('alert').filter({ hasText: 'no room left' })).toBeVisible()
  page.once('dialog', (dialog) => dialog.accept())
  await page.reload()
  await expect(page.getByRole('status', { name: 'Drawing elements' })).toHaveText('1 shapes')
  await page.evaluate(() => { sessionStorage.removeItem('proof-fail-board-write'); window.dispatchEvent(new Event('online')) })
  await expect(page.getByText(/^Saved/).first()).toBeVisible()
  await page.reload()
  await expect(page.getByRole('status', { name: 'Drawing elements' })).toHaveText('1 shapes')
})
