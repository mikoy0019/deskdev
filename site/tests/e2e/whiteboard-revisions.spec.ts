test('DM replies survive reload and sending keeps the composer focused', async ({ page }) => {
  await page.goto('/workspace/messages')
  await page.getByRole('button', { name: 'New chat' }).first().click()
  await page.getByRole('option').filter({ hasText: 'Alex Cruz' }).first().click()
  await page.getByRole('button', { name: /Start chat/ }).click()
  const composer = page.getByLabel('Write a message')
  await composer.fill('Review the whiteboard revision')
  await composer.press('Enter')
  await expect(composer).toHaveValue('')
  await expect(composer).toBeFocused()
  await page.getByRole('button', { name: 'Reply to Maykie', exact: true }).click()
  await expect(page.getByText('Replying to:', { exact: false })).toBeVisible()
  await composer.fill('This is the follow-up')
  await composer.press('Enter')
  await expect(composer).toHaveValue('')
  await expect(composer).toBeFocused()
  await page.reload()
  await expect(page.getByRole('log').getByRole('button', { name: 'Review the whiteboard revision', exact: true })).toBeVisible()
  await expect(page.getByRole('log')).toContainText('This is the follow-up')
})

test('OLJ batch links and factual CV preparation persist', async ({ page }) => {
  await page.goto('/workspace/growth/applications')
  await page.getByLabel('Paste OnlineJobs.ph posting links').fill('https://onlinejobs.ph/jobseekers/job/React-Developer-123456\nhttps://www.onlinejobs.ph/jobseekers/job/React-Developer-123456?ref=duplicate')
  await page.getByRole('button', { name: 'Add posting links', exact: true }).click()
  const queue = page.getByRole('navigation', { name: 'Application queue' })
  await expect(queue.getByRole('button', { name: /React Developer 123456/ })).toHaveCount(1)
  await queue.getByRole('button', { name: /React Developer 123456/ }).click()
  await page.getByLabel('Job description', { exact: true }).fill('React developer. Python required.')
  await page.getByLabel('Source CV', { exact: true }).fill('Alex Cruz\nBuilt React dashboards for a client.')
  await page.getByRole('button', { name: 'Prepare CV draft', exact: true }).click()
  await expect(page.getByLabel('CV draft', { exact: true })).toHaveValue(/Built React dashboards for a client/)
  await expect(page.getByLabel('CV draft', { exact: true })).toHaveValue(/Do not claim python without evidence/)
  await page.getByLabel('Application status', { exact: true }).selectOption('ready')
  await page.getByRole('button', { name: 'Save application', exact: true }).click()
  await expect(page.getByText('Application saved', { exact: true })).toBeVisible()
  await page.reload()
  await queue.getByRole('button', { name: /React Developer 123456/ }).click()
  await expect(page.getByLabel('Application status', { exact: true })).toHaveValue('ready')
  await expect(page.getByLabel('Source CV', { exact: true })).toHaveValue(/Built React dashboards/)
})

test('saved Zoom links can be joined from Meetings and Home', async ({ page }) => {
  await page.goto('/workspace/meetings')
  await page.getByRole('button', { name: 'New meeting', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'New meeting', exact: true })
  await dialog.getByLabel('Title *', { exact: true }).fill('Whiteboard revision call')
  await dialog.getByLabel('Meeting link', { exact: true }).fill('https://zoom.us/j/123456789')
  await dialog.getByRole('button', { name: 'Create meeting', exact: true }).click()
  const join = page.getByRole('link', { name: 'Join meeting: Whiteboard revision call', exact: true })
  await expect(join).toHaveAttribute('href', 'https://zoom.us/j/123456789')
  await expect(join).toHaveAttribute('target', '_blank')
  await page.goto('/workspace')
  await expect(page.getByRole('link', { name: 'Join meeting: Whiteboard revision call', exact: true })).toHaveAttribute('href', 'https://zoom.us/j/123456789')
})
